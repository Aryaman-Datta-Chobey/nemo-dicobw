#!/usr/bin/env python
"""Sweep a minimum-speech filter on hypothesis speakers before the oracle-VAD fill (ESD-ON).

A hypothesis speaker is dropped when its speech is below max(A seconds, F x the recording's hypothesis
speech) (eval/crowd_eval.py min_speech_filter); its VAD frames are then reassigned by fill_nearest_vad.
Per system and (A, F): dev D1 / R1 DER and dev 4-speaker exact count (tuning), and crowd real / synth8
DER and missed-speaker rate (check that real low-airtime speakers are not removed). Each system is a list
of run dirs; a manifest's RTTMs are taken from the first dir that has rttm/<manifest stem>/.
Writes <out>/min_speech_sweep.{json,md}; choose (A, F) on dev, read the crowd columns as the regression check.

    python eval/min_speech_sweep.py --out results/20261028-ear1-min-speech \
        --system base=$EXP/20261028-ear1-crowd-base,$EXP/20261027-nemotron-ft-ear1/selection/base
"""
from __future__ import annotations

import argparse
import json
from concurrent.futures import ProcessPoolExecutor
from functools import partial
from pathlib import Path

from crowd_eval import metrics, one

DATA = Path("/mnt/data/manifests/nemo")
SETS = {"dev_D1": "ear1_dev_D1", "dev_R1": "ear1_dev_R1", "crowd_real": "ear1_crowd_real", "crowd_synth8": "ear1_crowd_synth8"}
ABS = [0.0, 5.0, 10.0, 20.0, 40.0]
FRAC = [0.0, 0.01, 0.02, 0.04]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--system", action="append", required=True, help="name=<run dir>[,<run dir>...]")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--jobs", type=int, default=6)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    systems = {k: [Path(x) for x in v.split(",")] for k, v in (s.split("=", 1) for s in args.system)}
    rows = {k: [json.loads(x) for x in (DATA / f"{v}.jsonl").read_text().splitlines() if x.strip()] for k, v in SETS.items()}

    result: dict = {"systems": {k: list(map(str, v)) for k, v in systems.items()}, "grid": []}
    with ProcessPoolExecutor(args.jobs) as ex:
        for name, dirs in systems.items():
            rdir = {k: next(d / "rttm" / v for d in dirs if (d / "rttm" / v).is_dir()) for k, v in SETS.items()}
            for a in ABS:
                for f in FRAC:
                    res, dev4 = {"system": name, "abs_s": a, "frac": f}, []
                    for k, rs in rows.items():
                        recs = [r["fill_nearest_vad"] for r in ex.map(
                            partial(one, rttm_dir=rdir[k], min_speech=(a, f), methods=["fill_nearest_vad"]), rs)]
                        res[k] = metrics(recs)
                        dev4 += [r for r in recs if k.startswith("dev") and r["n_ref"] == 4]
                    res["dev_4spk_exact"] = sum(r["err"] == 0 for r in dev4) / len(dev4)
                    result["grid"].append(res)
                    print(f"{name} A={a:g} F={f:g}: dev {100 * res['dev_D1']['der']:.2f}/{100 * res['dev_R1']['der']:.2f} "
                          f"4spk {100 * res['dev_4spk_exact']:.0f}% crowd {100 * res['crowd_real']['der']:.2f}/"
                          f"{100 * res['crowd_synth8']['der']:.2f}", flush=True)
    (args.out / "min_speech_sweep.json").write_text(json.dumps(result, indent=1))

    md = ["# Minimum-speech filter sweep (before the oracle-VAD fill)", "",
          "Drop a hypothesis speaker with speech < max(A s, F × hypothesis speech). DER % after fill_nearest_vad, collar 0; "
          "exact = speaker count; missed = reference speakers with recall < 5%. Tune on dev, crowd = regression check. "
          "Generated by eval/min_speech_sweep.py.", "",
          "| system | A (s) | F | dev D1 | dev R1 | dev mean | dev 4-spk exact | dev exact D1 / R1 | crowd real DER / missed | crowd synth8 DER / missed | synth8 exact |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in result["grid"]:
        md.append(f"| {r['system']} | {r['abs_s']:g} | {r['frac']:g} | {100 * r['dev_D1']['der']:.2f} | {100 * r['dev_R1']['der']:.2f} | "
                  f"{50 * (r['dev_D1']['der'] + r['dev_R1']['der']):.2f} | {100 * r['dev_4spk_exact']:.0f}% | "
                  f"{100 * r['dev_D1']['exact']:.0f}% / {100 * r['dev_R1']['exact']:.0f}% | "
                  f"{100 * r['crowd_real']['der']:.2f} / {100 * r['crowd_real']['missed_rate']:.1f}% | "
                  f"{100 * r['crowd_synth8']['der']:.2f} / {100 * r['crowd_synth8']['missed_rate']:.1f}% | "
                  f"{100 * r['crowd_synth8']['exact']:.0f}% |")
    (args.out / "min_speech_sweep.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
