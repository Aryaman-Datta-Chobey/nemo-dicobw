#!/usr/bin/env python
"""Speaker-count outcomes by gold speaker count, without and with the oracle-VAD fill.

For each system (name=<rttm root>, <root>/<condition>/<uniq_id>.rttm) and each manifest, every
recording is scored at collar 0 with eval/vad_postproc.py's methods base and fill_nearest_vad. Per
system x method x gold count (speakers with scored reference time): recordings, exact count %,
within +-1 %, mean count bias (hyp - ref), DER. Rows are pooled over the given manifests and also
reported per manifest. Writes <out>/count_by_gold.{json,md}.

    python eval/count_by_gold.py --out results/20261028-nemotron-ft-ear1-gate \
        --system base=$EXP/selection/base/rttm --system ft=$EXP/selection/<ckpt>/rttm \
        --manifest $DATA/manifests/nemo/ear1_dev_D1.jsonl --manifest $DATA/manifests/nemo/ear1_dev_R1.jsonl
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from concurrent.futures import ProcessPoolExecutor
from functools import partial
from pathlib import Path

import numpy as np

from nemo_dicobw.diar_metrics import DiarSummary
from vad_postproc import one

METHODS = ["base", "fill_nearest_vad"]


def rows_for(recs: list[dict]) -> dict[str, dict]:
    by: dict[int, list[dict]] = defaultdict(list)
    for r in recs:
        by[r["n_ref"]].append(r)
    out = {}
    for g in sorted(by) + ["all"]:
        rs = recs if g == "all" else by[g]
        err = np.array([r["n_hyp"] - r["n_ref"] for r in rs])
        der = DiarSummary({r["uid"]: r["score"] for r in rs}).overall()["der"]
        out[str(g)] = {"n": len(rs), "exact": float(np.mean(err == 0)), "pm1": float(np.mean(np.abs(err) <= 1)),
                       "bias": float(err.mean()), "der": der}
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--system", action="append", required=True, help="name=<rttm root>")
    ap.add_argument("--manifest", action="append", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--jobs", type=int, default=8)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    systems = dict(s.split("=", 1) for s in args.system)

    recs: dict[str, dict[str, list[dict]]] = {s: {m: [] for m in METHODS} for s in systems}
    with ProcessPoolExecutor(args.jobs) as ex:
        for sys_name, root in systems.items():
            for man in args.manifest:
                rows = [json.loads(x) for x in man.read_text().splitlines() if x.strip()]
                fn = partial(one, rttm_dir=Path(root) / man.stem, probs_dir=None, ms=METHODS)
                for p in ex.map(fn, rows):
                    for m in METHODS:
                        s = p["scores"][m]
                        recs[sys_name][m].append({"uid": p["uid"], "cond": man.stem, "score": s,
                                                  "n_ref": s.n_ref_speakers, "n_hyp": s.n_hyp_speakers})

    conds = [m.stem for m in args.manifest]
    result = {"systems": systems, "manifests": [str(m) for m in args.manifest], "collar": 0.0, "tables": {}}
    for s in systems:
        for m in METHODS:
            rs = recs[s][m]
            result["tables"][f"{s}/{m}"] = {"pooled": rows_for(rs),
                                           **{c: rows_for([r for r in rs if r["cond"] == c]) for c in conds}}
    (args.out / "count_by_gold.json").write_text(json.dumps(result, indent=1))

    md = ["# Speaker count by gold speaker count", "",
          "Per recording, collar 0; exact / ±1 = % of recordings, bias = mean (hyp − ref) speakers, DER % pooled. "
          "fill_nearest_vad = oracle-VAD fill (eval/vad_postproc.py). Generated by eval/count_by_gold.py.", ""]
    for scope in ["pooled", *conds]:
        md += [f"## {scope}", "", "| system | method | gold | n | exact | ±1 | bias | DER |", "|---|---|---|---|---|---|---|---|"]
        for key, t in result["tables"].items():
            s, m = key.split("/")
            for g, r in t[scope].items():
                md.append(f"| {s} | {m} | {g} | {r['n']} | {100 * r['exact']:.0f} | {100 * r['pm1']:.0f} | "
                          f"{r['bias']:+.2f} | {100 * r['der']:.2f} |")
        md.append("")
    (args.out / "count_by_gold.md").write_text("\n".join(md))
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
