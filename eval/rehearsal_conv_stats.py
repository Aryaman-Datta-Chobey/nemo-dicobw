"""Conversation-structure statistics of the rehearsal labels of the Nemotron EAR-1 fine-tuning mixes vs EAR-1.

Runs eval/conversation_stats.py's per-session statistics on the reference RTTMs the fine-tuning actually uses as
labels (no transcripts exist for the rehearsal train splits), so only the timing / turn-taking features are
computed; the text features (backchannels, speaking rate, fillers, Latin share, digits, punctuation) are NaN
and left out of the distances. Units are RTTM files: one per session, except NOTSOFAR (one per device).

    reh_<corpus>   distinct rehearsal RTTMs of any nemotron_ft/*/train.json (via the manifests written by
                   eval/rehearsal_audio_char.py manifests)
    mix_<mix>      rehearsal lines of that mix (repeated lines / channels of one session count again)
    ear1_<split>_fa / _seg   EAR-1 on fa refs (fine-tuning labels) and segment refs (20261027 convention)

Label conventions differ by corpus (fa: AliMeeting, NOTSOFAR, AMI, EAR-1; segments: AISHELL-4 train; word timings
merged across gaps: ICSI), which shifts segment and gap statistics; turn statistics (gaps <= 0.5 s merged) are
less sensitive.

    PYTHONPATH=eval python eval/rehearsal_conv_stats.py --out results/20261030-rehearsal-conv-stats
"""
from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

from conversation_stats import DISTANCE_KEYS, session_stats, table
from nemo_dicobw.rttm import load_rttm

TEXT_KEYS = ("bc_pct", "bc_per_min", "bc_inside_pct", "tok_per_s", "filler_per_100", "latin_pct", "digit_seg_pct",
             "punct_seg_pct")
TIMING_KEYS = [k for k in DISTANCE_KEYS if k not in TEXT_KEYS]
TARGETS = ["ear1_train_fa", "ear1_dev_fa"]


def rttm_stats(path: Path) -> dict:
    (sess, turns), = load_rttm([path]).items()
    segs = [{"speaker": t.speaker, "start_time": t.start, "end_time": t.end, "words": ""} for t in turns]
    r = session_stats(segs)
    r.update({k: math.nan for k in TEXT_KEYS})
    return {"session": sess, "rttm": str(path), **{k: (round(v, 4) if isinstance(v, float) else v) for k, v in r.items()}}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest-dir", type=Path, default=Path("/mnt/data/manifests/nemo/rehearsal_audio_char"))
    ap.add_argument("--ft-dir", type=Path, default=Path("/mnt/data/manifests/nemotron_ft"))
    ap.add_argument("--ear1-refs", type=Path, default=Path("/mnt/data/refs/ear1"))
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    rows: dict[str, list[dict]] = {}
    for split in ("train", "dev"):
        for conv, sub in (("fa", "fa"), ("seg", "segments")):
            rows[f"ear1_{split}_{conv}"] = [rttm_stats(p) for p in sorted((args.ear1_refs / split / "rttm" / sub).glob("*.rttm"))]
    by_rttm: dict[str, dict] = {}
    for mf in sorted(args.manifest_dir.glob("reh_*.jsonl")):
        paths = sorted({json.loads(x)["rttm_filepath"] for x in mf.read_text().splitlines()})
        rows[mf.stem] = [by_rttm.setdefault(p, rttm_stats(Path(p))) for p in paths]
    for mf in sorted(args.ft_dir.glob("*/train.json")):
        pool = [by_rttm[r["rttm_filepath"]] for r in map(json.loads, mf.read_text().splitlines())
                if not r["corpus"].startswith("ear1")]
        if pool:
            rows[f"mix_{mf.parent.name}"] = pool
    for name, rs in rows.items():
        (args.out / f"{name}.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rs))
        print(f"{name}: {len(rs)}", flush=True)
    md = table(rows, TARGETS, TIMING_KEYS)
    md = md.replace("# Conversation-structure statistics of transcript references",
                    "# Conversation structure of fine-tuning labels: rehearsal corpora and mixes vs EAR-1", 1)
    md = md.replace("Median [IQR] over sessions. Generated by eval/conversation_stats.py.",
                    "Median [IQR] over RTTM files (timing features only; text columns are empty). "
                    "Generated by eval/rehearsal_conv_stats.py.", 1)
    (args.out / "summary.md").write_text(md)
    print(f"wrote {args.out / 'summary.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
