#!/usr/bin/env python
"""Fine-tuning direction of Nemotron checkpoints: size and cosine similarity of the weight change from base.

For each checkpoint F (--ckpt name=path, a Lightning .ckpt), delta = W_F - W_B over the floating-point weights
of each module group of eval/drift_diag.py (lower encoder, upper encoder, head) and over all of them. Reports
the relative change ||delta|| / ||W_B|| and the pairwise cosine between deltas, per group. Two runs whose
deltas are parallel moved the model the same way (one may just be further along); a low cosine means the
training data sent them elsewhere. All in float32 (the released base is bf16). CPU only.
Writes <out>/ft_direction.{json,md}.

    python eval/ft_direction.py --out results/20261029-nemotron-ft-ear1-t2-diag/direction \
        --ckpt A-fa_s250=<run>/checkpoints/<epoch=0>.ckpt --ckpt A-fa-t2r25_s250=<run>/checkpoints/<epoch=0>.ckpt
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import torch

from drift_diag import GROUPS, base_state, ft_state


def deltas(base: dict, ft: dict) -> dict[str, torch.Tensor]:
    keys = [k for k in ft if ft[k].is_floating_point() and k in base]
    out = {g: torch.cat([(ft[k].float() - base[k].float()).flatten() for k in keys if f(k)]) for g, f in GROUPS.items()}
    out["all"] = torch.cat([(ft[k].float() - base[k].float()).flatten() for k in keys])
    return out


def norms(base: dict) -> dict[str, float]:
    keys = [k for k in base if base[k].is_floating_point()]
    out = {g: torch.cat([base[k].float().flatten() for k in keys if f(k)]).norm().item() for g, f in GROUPS.items()}
    out["all"] = torch.cat([base[k].float().flatten() for k in keys]).norm().item()
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ckpt", action="append", required=True, help="name=<Lightning .ckpt>")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    base = base_state()
    bn = norms(base)
    names, d = [], {}
    for spec in args.ckpt:
        name, path = spec.split("=", 1)
        names.append(name)
        d[name] = deltas(base, ft_state(Path(path)))
    groups = list(bn)
    rel = {n: {g: d[n][g].norm().item() / bn[g] for g in groups} for n in names}
    cos = {g: {a: {b: torch.nn.functional.cosine_similarity(d[a][g], d[b][g], dim=0).item() for b in names} for a in names}
           for g in groups}
    (args.out / "ft_direction.json").write_text(json.dumps({"ckpts": dict(s.split("=", 1) for s in args.ckpt),
                                                           "relative_change": rel, "cosine": cos}, indent=1))
    md = ["# Fine-tuning direction", "", "Relative weight change ||W - W_base|| / ||W_base|| (%) per module group, and cosine "
          "between the weight changes of two checkpoints. Generated by eval/ft_direction.py.", "",
          "| checkpoint | " + " | ".join(groups) + " |", "|---|" + "---|" * len(groups)]
    md += [f"| {n} | " + " | ".join(f"{100 * rel[n][g]:.3f}" for g in groups) + " |" for n in names]
    for g in groups:
        md += ["", f"## Cosine, {g}", "", "| | " + " | ".join(names) + " |", "|---|" + "---|" * len(names)]
        md += [f"| {a} | " + " | ".join(f"{cos[g][a][b]:.2f}" for b in names) + " |" for a in names]
    (args.out / "ft_direction.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
