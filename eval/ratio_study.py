#!/usr/bin/env python
"""Rehearsal-ratio study over every scored checkpoint family of arm A / fa labels (see EXPERIMENTS.md,
20261030-nemotron-ft-ear1-ratio-study). Families (seed 42 and -seed43 runs pooled) and their rehearsal share of lines:
r0 0, A-fa 0.088, t2r25 0.25, t2r50 0.50, r75a / r75b 0.75 (lines = sampled windows; effective batch 32).

  weights  per checkpoint: relative weight change ||W - W_base|| / ||W_base|| per module group (eval/drift_diag.py
           GROUPS) and per encoder layer, and the cosine of W - W_base to the reference direction (mean of the two A-fa
           seeds' changes at s1250) -> <out>/weights.{json,md}
  metrics  from <arms>/arms.md: per family x step the mean and range over seeds of dev / held-out / 4-spk / crowd score /
           AliMeeting and NOTSOFAR gate deltas, next to EAR-1 exposure (windows = step x 32 x EAR-1 share) and the
           cumulative EAR-1 update sum_t lr(t) x 32 x EAR-1 share (lr: linear warmup over 300 steps to 1e-5, then
           1e-5 sqrt(301 / (t + 1)); approximate); late means over steps >= 500; soup-* rows (seed averages, built by
           eval/ratio_soup.py) against their two seeds -> <out>/metrics.{json,md}

    python eval/ratio_study.py weights --arms results/20261028-nemotron-ft-ear1-v2 --out results/20261030-nemotron-ft-ear1-ratio-study
    python eval/ratio_study.py metrics --arms results/20261028-nemotron-ft-ear1-v2 --out results/20261030-nemotron-ft-ear1-ratio-study
"""
from __future__ import annotations

import argparse
import json
import re
import statistics
from pathlib import Path

SHARE = {"r0": 0.0, "A-fa": 34 / 386, "t2r25": 117 / 469, "t2r50": 353 / 705, "r75a": 0.75, "r75b": 0.75}
NAME = re.compile(r"^(soup-)?A-fa(?:-(r0|t2r25|t2r50|r75a|r75b))?(-seed43)?_s(\d+)$")
COLS = ["dev", "held", "4-spk", "score", "AliMeeting Δ", "NOTSOFAR Δ"]


def parse(name: str) -> tuple[str, str, int, bool] | None:
    m = NAME.match(name)
    if not m:
        return None
    return m[2] or "A-fa", "43" if m[3] else "42", int(m[4]), bool(m[1])


def lr(t: int) -> float:
    return 1e-5 * min((t + 1) / 301, (301 / (t + 1)) ** 0.5)


def exposure(fam: str, step: int) -> tuple[float, float]:
    share = 1 - SHARE[fam]
    return step * 32 * share, sum(lr(t) for t in range(step)) * 32 * share


def weights(args) -> None:
    import torch
    from drift_diag import GROUPS, base_state, ft_state

    arms = json.loads((args.arms / "arms.json").read_text())
    ckpts = {n: Path(v["ckpt"]) for n, v in arms.items() if (p := parse(n)) and not p[3] and Path(str(v.get("ckpt", ""))).exists()}
    base = {k: v.float() for k, v in base_state().items() if v.is_floating_point()}
    keys = sorted(base)
    layer = lambda k: int(m[1]) if (m := re.match(r"encoder\.layers\.(\d+)\.", k)) else None
    flat = lambda sd: torch.cat([(sd[k].float() - base[k]).flatten() for k in keys])
    ref = (flat(ft_state(ckpts["A-fa_s1250"])) + flat(ft_state(ckpts["A-fa-seed43_s1250"]))) / 2
    rows = {}
    for name in sorted(ckpts, key=lambda n: (parse(n)[0], parse(n)[1], parse(n)[2])):
        sd = ft_state(ckpts[name])
        d = flat(sd)
        rel = {g: (torch.cat([(sd[k].float() - base[k]).flatten() for k in keys if f(k)]).norm()
                   / torch.cat([base[k].flatten() for k in keys if f(k)]).norm()).item() for g, f in GROUPS.items()}
        rel["all"] = (d.norm() / torch.cat([base[k].flatten() for k in keys]).norm()).item()
        per_layer = {}
        for i in sorted({layer(k) for k in keys} - {None}):
            ks = [k for k in keys if layer(k) == i]
            per_layer[i] = (torch.cat([(sd[k].float() - base[k]).flatten() for k in ks]).norm()
                            / torch.cat([base[k].flatten() for k in ks]).norm()).item()
        fam, seed, step, _ = parse(name)
        rows[name] = {"family": fam, "seed": seed, "step": step, "exposure": exposure(fam, step)[0], "relative": rel,
                      "per_layer": per_layer, "cos_ref": torch.nn.functional.cosine_similarity(d, ref, dim=0).item()}
        print(name, f"{100 * rel['all']:.3f}%", f"cos_ref {rows[name]['cos_ref']:.2f}", flush=True)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "weights.json").write_text(json.dumps(rows, indent=1))
    layers = sorted(next(iter(rows.values()))["per_layer"])
    md = ["# Weight change by rehearsal ratio", "", "Relative change ||W - W_base|| / ||W_base|| (%) per module group and per encoder "
          "layer (every 4th shown; all in weights.json); cos_ref = cosine of W - W_base to the mean A-fa (seeds 42, 43) change at "
          "s1250. EAR-1 windows = step x 32 x EAR-1 share. Generated by eval/ratio_study.py weights.", "",
          "| checkpoint | EAR-1 windows | lower | upper | head | all | cos_ref | " + " | ".join(f"L{i}" for i in layers[::4]) + " |",
          "|---|---|---|---|---|---|---|" + "---|" * len(layers[::4])]
    for n, r in rows.items():
        md.append(f"| {n} | {r['exposure'] / 1000:.1f}k | " + " | ".join(f"{100 * r['relative'][g]:.3f}" for g in ("lower", "upper", "head", "all"))
                  + f" | {r['cos_ref']:.2f} | " + " | ".join(f"{100 * r['per_layer'][i]:.3f}" for i in layers[::4]) + " |")
    (args.out / "weights.md").write_text("\n".join(md) + "\n")


def arms_table(path: Path) -> dict[str, dict[str, float]]:
    """First table of arms.md: checkpoint | dev | dev fa | held | 4-spk | crowd real | crowd synth8 | score | AliMeeting Δ | NOTSOFAR Δ | drift."""
    lines = path.read_text().splitlines()
    head = next(i for i, l in enumerate(lines) if l.startswith("| checkpoint | dev | dev fa |"))
    cols = [c.strip() for c in lines[head].strip("|").split("|")]
    out = {}
    for l in lines[head + 2:]:
        if not l.startswith("|"):
            break
        cells = dict(zip(cols, (c.strip() for c in l.strip("|").split("|"))))
        num = lambda s: float(s.split()[0].rstrip("%").replace("+", ""))
        out[cells["checkpoint"]] = {c: num(cells[c]) for c in COLS}
    return out


def metrics(args) -> None:
    table = arms_table(args.arms / "arms.md")
    fams: dict[tuple[str, int], dict[str, dict]] = {}
    soups = {}
    for name, vals in table.items():
        if (p := parse(name)) is None:
            continue
        fam, seed, step, soup = p
        if soup:
            soups[(fam, step)] = vals
        else:
            fams.setdefault((fam, step), {})[seed] = vals
    rows = []
    for (fam, step), seeds in sorted(fams.items(), key=lambda x: (SHARE[x[0][0]], x[0][0], x[0][1])):
        exp, cum = exposure(fam, step)
        agg = {c: (statistics.mean(s[c] for s in seeds.values()), min(s[c] for s in seeds.values()), max(s[c] for s in seeds.values()))
               for c in COLS}
        rows.append({"family": fam, "share": SHARE[fam], "step": step, "seeds": sorted(seeds), "exposure": exp, "cum_update": cum,
                     "metrics": agg, "soup": soups.get((fam, step))})
    late = {}
    for fam in SHARE:
        r = [x for x in rows if x["family"] == fam and x["step"] >= 500 and len(x["seeds"]) == 2]
        if r:
            late[fam] = {"steps": [x["step"] for x in r], **{c: statistics.mean(x["metrics"][c][0] for x in r) for c in COLS}}
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "metrics.json").write_text(json.dumps({"rows": rows, "late": late}, indent=1))
    f = lambda m: f"{m[0]:.2f} [{m[1]:.2f}, {m[2]:.2f}]"
    md = ["# Rehearsal ratio: metrics by family and step", "", "Mean [min, max] over seeds (42, 43) of the arms.md columns (dev / held: DER "
          "after the oracle-VAD fill; 4-spk: dev 4-speaker exact count %; score: crowd score; gate deltas vs base). EAR-1 windows = step "
          "x 32 x EAR-1 share; cumulative update = sum_t lr(t) x 32 x EAR-1 share (approximate schedule). Generated by eval/ratio_study.py "
          "metrics.", "", "## Late mean (steps >= 500, both seeds)", "", "| family | share | steps | " + " | ".join(COLS) + " |",
          "|---|---|---|" + "---|" * len(COLS)]
    md += [f"| {fam} | {SHARE[fam]:.3f} | {v['steps'][0]}–{v['steps'][-1]} ({len(v['steps'])}) | " + " | ".join(f"{v[c]:.2f}" for c in COLS) + " |"
           for fam, v in late.items()]
    md += ["", "## By step", "", "| family | step | seeds | EAR-1 windows | cum. update | " + " | ".join(COLS) + " | soup " + " / ".join(COLS[:4]) + " |",
           "|---|---|---|---|---|" + "---|" * (len(COLS) + 1)]
    for r in rows:
        s = r["soup"]
        md.append(f"| {r['family']} | {r['step']} | {','.join(r['seeds'])} | {r['exposure'] / 1000:.1f}k | {1e3 * r['cum_update']:.2f} | "
                  + " | ".join(f(r["metrics"][c]) for c in COLS) + " | "
                  + (" / ".join(f"{s[c]:.2f}" for c in COLS[:4]) if s else "") + " |")
    (args.out / "metrics.md").write_text("\n".join(md) + "\n")
    print("\n".join(md[:12 + len(late)]))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("stage", choices=["weights", "metrics"])
    ap.add_argument("--arms", type=Path, required=True, help="results dir with arms.{json,md} (eval/score_ft_arms.py)")
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    {"weights": weights, "metrics": metrics}[args.stage](args)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
