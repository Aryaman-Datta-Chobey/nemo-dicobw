#!/usr/bin/env python
"""Active speakers per training-length window in reference RTTMs, to compare with eval/train_sample_stats.py.

The fine-tuning loss sees windows of at most ~105 s (one subsegment per manifest line per pass), and the
speaker count it learns as a prior is the number of speakers active in such a window, not in the recording.
This slides a --win s window with --hop s over every distinct reference RTTM of each manifest and counts the
speakers with any speech in the window (the same "active" rule as the training targets: any frame).
Also reports the recording-level gold count. Writes <out>/window_counts.{json,md}.

    python eval/window_counts.py --out results/20261029-ear1-window-counts \
        --set "EAR-1 dev=$DATA/manifests/nemo/ear1_dev_D1.jsonl" ...
"""
from __future__ import annotations

import argparse
import json
from collections import Counter
from pathlib import Path

from nemo_dicobw.rttm import load_rttm


def windows(turns, win: float, hop: float) -> list[int]:
    end = max(t.end for t in turns)
    starts = [0.0] if end <= win else [i * hop for i in range(int((end - win) / hop) + 1)]
    return [len({t.speaker for t in turns if t.start < s + win and t.end > s}) for s in starts]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--set", action="append", required=True, help="name=<manifest .json/.jsonl with rttm_filepath>")
    ap.add_argument("--win", type=float, default=105.0)
    ap.add_argument("--hop", type=float, default=15.0)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    args.out.mkdir(parents=True, exist_ok=True)
    res = {}
    for spec in args.set:
        name, man = spec.split("=", 1)
        rttms = sorted({json.loads(x)["rttm_filepath"] for x in Path(man).read_text().splitlines() if x.strip()})
        win, rec = Counter(), Counter()
        for p in rttms:
            for turns in load_rttm([Path(p)]).values():
                if turns:
                    win.update(windows(turns, args.win, args.hop))
                    rec[len({t.speaker for t in turns})] += 1
        res[name] = {"recordings": sum(rec.values()), "windows": sum(win.values()), "rec": dict(sorted(rec.items())), "win": dict(sorted(win.items()))}
    (args.out / "window_counts.json").write_text(json.dumps({"win": args.win, "hop": args.hop, "sets": res}, indent=1))
    pct = lambda c, k, n: f"{100 * c.get(k, 0) / n:.0f}"
    md = ["# Active speakers per window vs per recording", "",
          f"% of {args.win:g} s windows (hop {args.hop:g} s) with k speakers active (any speech), and % of recordings with k gold speakers. "
          "One count per distinct reference RTTM (views of a session share it). Generated by eval/window_counts.py.", "",
          "| set | unit | n | " + " | ".join(f"{k}" for k in range(1, 9)) + " | ≥9 |", "|---|---|---|" + "---|" * 9]
    for name, r in res.items():
        for unit, key, n in (("windows", "win", r["windows"]), ("recordings", "rec", r["recordings"])):
            c = {int(k): v for k, v in r[key].items()}
            md.append(f"| {name} | {unit} | {n} | " + " | ".join(pct(c, k, n) for k in range(1, 9)) +
                      f" | {100 * sum(v for k, v in c.items() if k >= 9) / n:.0f} |")
    (args.out / "window_counts.md").write_text("\n".join(md) + "\n")
    print("\n".join(md))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
