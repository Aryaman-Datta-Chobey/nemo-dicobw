#!/usr/bin/env python
"""Score every condition of a diarization run and write a summary table.

For each <run>/rttm/<condition>/ with a manifest at <manifests>/<condition>.jsonl, writes
<results>/<run_id>/<condition>[__<variant>].{json,md} via eval/score_diar.py:
    (main)     the manifest's reference (fa > words > segments) and full-recording UEM
    __nouem    fa reference without UEM: the Nemotron model card's protocol (only where fa exists)
    __segments segment-level reference with UEM (only where the manifest uses another type)
and <results>/<run_id>/summary.md, generated from those JSONs.

Example:
    python eval/score_diar_run.py --run-dir $DATA/exp/nemotron/20261026-nemotron-zeroshot
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

from nemo_dicobw.diar_report import summary_table

REPO = Path(__file__).resolve().parents[1]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-dir", type=Path, required=True)
    ap.add_argument("--manifests", type=Path, default=Path("/mnt/data/manifests/nemo"))
    ap.add_argument("--results", type=Path, default=REPO / "results")
    ap.add_argument("--conditions", nargs="*", help="default: every condition in the run")
    args = ap.parse_args()

    run_id = args.run_dir.name
    out_dir = args.results / run_id
    out_dir.mkdir(parents=True, exist_ok=True)
    config = json.loads((args.run_dir / "config.json").read_text())
    conds = args.conditions or sorted(p.name for p in (args.run_dir / "rttm").iterdir() if p.is_dir())

    for cond in conds:
        manifest = args.manifests / f"{cond}.jsonl"
        rows = [json.loads(line) for line in manifest.read_text().splitlines() if line.strip()]
        ref_type = rows[0]["ref_type"]
        ref_root = Path(rows[0]["rttm_filepath"]).parents[1]
        variants = [("", [], ref_type)]
        if ref_type == "fa":
            variants.append(("__nouem", ["--no-uem"], "fa"))
        if ref_type != "segments" and (ref_root / "segments").is_dir():
            variants.append(("__segments", ["--ref", str(ref_root / "segments")], "segments"))
        for suffix, extra, rt in variants:
            name = f"{cond}{suffix}"
            cmd = [sys.executable, str(REPO / "eval" / "score_diar.py"), "--manifest", str(manifest),
                   "--hyp", str(args.run_dir / "rttm" / cond), "--name", f"{run_id}/{name}",
                   "--out", str(out_dir / f"{name}.json"), *extra,
                   "--meta", f"condition={name}", f"ref_type={rt}", f"run={run_id}",
                   f"model={config['model']}", f"precision={config['precision']}",
                   f"streaming={json.dumps(config['streaming'], separators=(',', ':'))}"]
            subprocess.run(cmd, check=True, stdout=subprocess.DEVNULL)
            print(f"scored {name}")

    results = [json.loads(p.read_text()) for p in sorted(out_dir.glob("*.json"))]
    md = [f"# {run_id}: diarization and speech-segmentation scores", "",
          f"Model `{config['model']}`, {config['precision']}, streaming {config['streaming']}; "
          f"{config['postprocessing']}. Overlap scored; percentages. Generated by eval/score_diar_run.py "
          "from the JSON files in this directory.", "",
          "`ref`: fa = published forced alignment, words = merged word timings, segments = corpus "
          "segment annotation. `UEM no` = scored first-to-last turn (Nemotron card protocol).", "",
          summary_table(results)]
    (out_dir / "summary.md").write_text("\n".join(md))
    print(f"wrote {out_dir / 'summary.md'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
