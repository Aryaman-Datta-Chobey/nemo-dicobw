"""Audio characteristics of the rehearsal parts of the Nemotron EAR-1 fine-tuning mixes vs EAR-1.

Two steps around eval/audio_characteristics.py (which does the per-recording analysis):

    manifests   one NeMo manifest per rehearsal corpus with every distinct rehearsal recording used by any
                fine-tuning mix in --ft-dir (<mix>/train.json, EAR-1 lines skipped), with uniq_id / session /
                channel and the list of mixes using it; plus EAR-1 train/dev D1 / R1 / H_all manifests on the
                fa references (the fine-tuning label convention; the 20261027 analysis used segment refs).
    summary     per-corpus and per-mix summaries: each mix pools its rehearsal lines (repeats count), so the
                medians are those of the rehearsal audio as sampled by that mix; distances to the EAR-1 targets
                as in audio_characteristics.summarise (features z-scored over all rows passed).

    python eval/rehearsal_audio_char.py manifests --out-dir /mnt/data/manifests/nemo/rehearsal_audio_char
    PYTHONPATH=eval python eval/audio_characteristics.py --jobs 6 --out <res> <out-dir>/*.jsonl
    PYTHONPATH=eval python eval/rehearsal_audio_char.py summary --res <res> --manifest-dir <out-dir>
"""
from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

from audio_characteristics import summarise

EAR1_TARGETS = [f"ear1fa_{s}_{c}" for s in ("train", "dev") for c in ("D1", "R1", "H_all")]


def rec_id(audio: str) -> str:
    p = Path(audio)
    return f"{p.parent.name}__{p.stem}"


def rttm_session(path: str) -> str:
    ids = {ln.split()[1] for ln in open(path) if ln.startswith("SPEAKER")}
    if len(ids) != 1:
        raise ValueError(f"{path}: expected one file id, found {sorted(ids)[:5]}")
    return ids.pop()


def cmd_manifests(args: argparse.Namespace) -> int:
    args.out_dir.mkdir(parents=True, exist_ok=True)
    recs: dict[str, dict] = {}
    for mf in sorted(args.ft_dir.glob("*/train.json")):
        mix = mf.parent.name
        for line in mf.read_text().splitlines():
            r = json.loads(line)
            if r["corpus"].startswith("ear1"):
                continue
            assert r["offset"] == 0, (mf, r)
            uid = rec_id(r["audio_filepath"])
            row = recs.setdefault(uid, {
                "audio_filepath": r["audio_filepath"], "uniq_id": uid, "offset": 0, "duration": r["duration"],
                "rttm_filepath": r["rttm_filepath"], "session": rttm_session(r["rttm_filepath"]),
                "channel": Path(r["audio_filepath"]).stem, "corpus": r["corpus"], "mixes": []})
            if mix not in row["mixes"]:
                row["mixes"].append(mix)
    by_corpus: dict[str, list[dict]] = defaultdict(list)
    for row in recs.values():
        by_corpus[row["corpus"]].append(row)
    for corpus, rows in sorted(by_corpus.items()):
        (args.out_dir / f"reh_{corpus}.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))
        print(f"reh_{corpus}: {len(rows)} recordings, {sum(r['duration'] for r in rows) / 3600:.1f} h")
    for split in ("train", "dev"):
        for ch in ("D1", "R1", "H_all"):
            rows = [json.loads(x) for x in (args.nemo_dir / f"ear1_{split}_{ch}.jsonl").read_text().splitlines()]
            for r in rows:
                r["rttm_filepath"] = r["rttm_filepath"].replace("/rttm/segments/", "/rttm/fa/")
                assert Path(r["rttm_filepath"]).exists(), r["rttm_filepath"]
                r["ref_type"] = "fa"
            (args.out_dir / f"ear1fa_{split}_{ch}.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows))
            print(f"ear1fa_{split}_{ch}: {len(rows)} recordings")
    return 0


def cmd_summary(args: argparse.Namespace) -> int:
    rows: dict[str, list[dict]] = {}
    feats: dict[str, dict] = {}
    for f in sorted(args.res.glob("*.jsonl")):
        rows[f.stem] = [json.loads(x) for x in f.read_text().splitlines()]
        if f.stem.startswith("reh_"):
            feats.update({r["uniq_id"]: r for r in rows[f.stem]})
    # per-mix pools: rehearsal lines as sampled by the mix (repeated lines count again)
    for mf in sorted(args.ft_dir.glob("*/train.json")):
        pool = [feats[rec_id(r["audio_filepath"])] for r in map(json.loads, mf.read_text().splitlines())
                if not r["corpus"].startswith("ear1")]
        rows[f"mix_{mf.parent.name}"] = pool
    md = summarise(rows, [t for t in EAR1_TARGETS if t in rows])
    md = md.replace("# Audio characteristics of diarization inputs",
                    "# Audio characteristics: fine-tuning rehearsal corpora and mixes vs EAR-1 (fa refs)", 1)
    md = md.replace("Generated by eval/audio_characteristics.py.",
                    "Generated by eval/rehearsal_audio_char.py summary. `reh_*` = distinct rehearsal recordings "
                    "per corpus; `mix_*` = rehearsal lines of that fine-tuning mix; `ear1fa_*` = EAR-1 on fa refs.", 1)
    (args.res / "summary.md").write_text(md)
    print(f"wrote {args.res / 'summary.md'}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    m = sub.add_parser("manifests")
    m.add_argument("--ft-dir", type=Path, default=Path("/mnt/data/manifests/nemotron_ft"))
    m.add_argument("--nemo-dir", type=Path, default=Path("/mnt/data/manifests/nemo"))
    m.add_argument("--out-dir", type=Path, required=True)
    s = sub.add_parser("summary")
    s.add_argument("--ft-dir", type=Path, default=Path("/mnt/data/manifests/nemotron_ft"))
    s.add_argument("--res", type=Path, required=True)
    args = ap.parse_args()
    return cmd_manifests(args) if args.cmd == "manifests" else cmd_summary(args)


if __name__ == "__main__":
    raise SystemExit(main())
